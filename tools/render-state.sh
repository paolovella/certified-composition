#!/usr/bin/env bash
# Regenerates STATE.md: the one file a new session (human or agent) reads first.
# Everything in it is derived from the repo (git, backlog/, AUTONOMY, receipts), never typed by
# hand, so it cannot drift from what is actually there.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

out=STATE.md
field() { sed -n "s/^$2: //p" "$1" | head -1; }

{
  echo "# STATE (generated by tools/render-state.sh, do not edit)"
  echo
  echo "- HEAD: \`$(git log -1 --format='%h %s')\`"
  echo "- branch: \`$(git rev-parse --abbrev-ref HEAD)\`, ahead/behind origin: \`$(git rev-list --left-right --count '@{u}...HEAD' 2>/dev/null | awk '{print "behind " $1 ", ahead " $2}' || echo 'no upstream')\`"
  echo "- AUTONOMY: \`$(cat AUTONOMY 2>/dev/null || echo missing)\`"
  dirty=$(git status --porcelain | grep -v ' STATE.md$' || true)
  if [ -n "$dirty" ]; then
    echo "- **working tree is dirty** ($(echo "$dirty" | wc -l) paths): commit it or record why it is abandoned before new work"
  else
    echo "- working tree clean"
  fi
  open_jobs=$(ls tools/receipts/*.start 2>/dev/null | while read -r s; do [ -f "${s%.start}.end" ] || echo "$s"; done || true)
  if [ -n "$open_jobs" ]; then
    echo "- **jobs with no end receipt (incident unless still running):**"
    echo "$open_jobs" | sed 's/^/  - /'
  fi
  echo
  for st in in-progress planned blocked done killed; do
    files=$(grep -l "^status: $st$" backlog/*.md 2>/dev/null || true)
    [ -z "$files" ] && continue
    echo "## $st"
    echo
    echo "| id | tier | title | deps |"
    echo "|---|---|---|---|"
    for f in $files; do
      echo "| $(field "$f" id) | $(field "$f" tier) | $(field "$f" title) | $(field "$f" deps) |"
    done
    echo
  done
  echo "Plan of record: PLAN-2026-10.md. Protocol: CLAUDE.md."
} > "$out"
echo "wrote $out"
